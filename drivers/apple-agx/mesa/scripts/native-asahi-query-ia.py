#!/usr/bin/env python3
"""RC67: count the IA statistics of an unrolled multi-draw indirect once.

Projected after the indirect-stream and query-timestamp projections. The
original kernel bundle is generated by generate-query-ia.py; the host helper
is mesa/winsys/agx_win32_query_ia.h. Native bodies stay intact: the unrolled
draws only skip the update the helper already made for their records.
"""
import hashlib
import json
import re


def once(text, old, new):
    if text.count(old) != 1:
        raise RuntimeError('Ambiguous query IA anchor: ' + old[:100])
    return text.replace(old, new, 1)


def generated(project):
    mesa = project / 'drivers/apple-agx/mesa'
    winsys = mesa / 'winsys'
    directory = winsys / 'query-ia-generated'
    manifest = json.loads((directory / 'manifest.json').read_text())
    for path in (winsys / 'agx_win32_query_ia.cl',
                 mesa / 'scripts/generate-query-ia.py'):
        if hashlib.sha256(path.read_bytes()).hexdigest() != manifest['inputs'][path.name]:
            raise RuntimeError('Regenerate query IA kernel after changing ' + path.name)
    for name, sha in manifest['outputs'].items():
        if hashlib.sha256((directory / name).read_bytes()).hexdigest() != sha:
            raise RuntimeError('Query IA generated output changed: ' + name)
    return directory


def project_library_c(text, project):
    if 'LIBAGX_WIN32_QUERY_IA_RECORDS' in text:
        raise RuntimeError('Query IA library was already projected')
    extra = (generated(project) / 'agx_win32_query_ia_shaders.c').read_text()
    begin = extra.index('static const uint32_t ')
    end = extra.index('const uint32_t *libagx_g13g[')
    text = once(text, '#include "libagx_shaders.h"',
                '#include "libagx_shaders.h"\n' + extra[begin:end])
    for chip in ('g13g', 'g13x'):
        anchor = 'const uint32_t *libagx_' + chip + '[LIBAGX_NUM_PROGRAMS] = {'
        entry = extra[extra.index(anchor) + len(anchor):].split('};', 1)[0]
        text = once(text, anchor, anchor + entry)
    return text


UNROLL = '''   if (indirect && indirect->draw_count > 1 && !indirect->indirect_draw_count) {
      assert(drawid_offset == 0);
      assert(num_draws == 1);

      util_draw_multi_unroll_indirect(pctx, info, indirect, draws);
      return;
   }'''

UNROLL_COUNTED = '''   if (indirect && indirect->draw_count > 1 && !indirect->indirect_draw_count) {
      assert(drawid_offset == 0);
      assert(num_draws == 1);

      /* RC67: one dispatch counts the IA statistics of every record; the
       * unrolled draws below skip their per-draw dispatch and CDM barrier. */
      bool windows_ia = agx_win32_query_ia_records(ctx, info, indirect);
      if (ctx->any_faults) return;
      bool outer_ia = ctx->windows_query_ia_records;
      ctx->windows_query_ia_records = outer_ia || windows_ia;
      util_draw_multi_unroll_indirect(pctx, info, indirect, draws);
      ctx->windows_query_ia_records = outer_ia;
      return;
   }'''


def project_sources(out, project, overlays):
    def save(path, text):
        (out / path).write_text(text)
        overlays.setdefault(path, {})['after_query_ia'] = (
            hashlib.sha256(text.encode()).hexdigest())

    extra = (generated(project) / 'agx_win32_query_ia_shaders.h').read_text()
    extra = extra[extra.index('struct libagx_win32_query_ia_records_args {'):]
    extra = re.sub(r'enum libagx_program \{.*?\};', '', extra, flags=re.S)
    extra = extra[:extra.index('extern const uint32_t *')]
    path = 'src/asahi/lib/libagx_shaders.h'
    text = (out / path).read_text()
    if 'LIBAGX_WIN32_QUERY_IA_RECORDS' in text:
        raise RuntimeError('Query IA header was already projected')
    text = once(text, '    LIBAGX_NUM_PROGRAMS,',
                '    LIBAGX_WIN32_QUERY_IA_RECORDS,\n    LIBAGX_NUM_PROGRAMS,')
    save(path, text + '\n' + extra)

    path = 'src/gallium/drivers/asahi/agx_state.h'
    text = (out / path).read_text()
    text = once(text, '   unsigned windows_indirect_encode_us;', '''   unsigned windows_indirect_encode_us;
   /* RC67: the records of the current unrolled multi-draw indirect are
    * already counted (agx_win32_query_ia.h). */
   unsigned windows_query_ia_records;''')
    save(path, text)

    path = 'src/gallium/drivers/asahi/agx_state.c'
    text = (out / path).read_text()
    text = once(text, '#include "agx_win32_counted_indirect.h"\n\nstatic void\nagx_draw_vbo_windows_body(',
                '#include "agx_win32_counted_indirect.h"\n#include "agx_win32_query_ia.h"\n\n'
                'static void\nagx_draw_vbo_windows_body(')
    split = text.index('static void\nagx_draw_vbo_windows_body(')
    head, body = text[:split], text[split:]
    body = once(body, UNROLL, UNROLL_COUNTED)
    body = once(body, '   if (!ctx->windows_indirect_stream && ctx->active_queries && !ctx->in_tess &&',
                '   if (!ctx->windows_indirect_stream && !ctx->windows_query_ia_records &&\n'
                '       ctx->active_queries && !ctx->in_tess &&')
    save(path, head + body)
