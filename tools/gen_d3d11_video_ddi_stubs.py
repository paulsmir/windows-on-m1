#!/usr/bin/env python3
"""gen_d3d11_video_ddi_stubs.py WDK_D3D10UMDDI_H OUT_INC

S2-1e step 0 (receipt-only): emit agx_d3d11_video_ddi.inc, one stub per member of the WDK 26100
D3DWDDM2_0DDI_VIDEODEVICEFUNCS table (d3d10umddi.h), with the exact typedef signature. Every stub logs
"measure-dxgi-video-ddi" {entry index, call count} (first 8 calls per entry, then power-of-two counts) and
answers "nothing supported": HRESULT entries E_NOTIMPL, SIZE_T entries a fixed private size, VOID entries
no-op, except the query entries listed in SPECIAL, which write an explicit zero / FALSE answer. The table
is filled by AgxWddm2_0RetrieveSubObject for D3DWDDM2_0DDI_VIDEO_FUNCTIONS (3)."""
import re, sys
src, out = sys.argv[1:]
h = open(src, encoding='latin-1').read()
m = re.search(r'typedef struct D3DWDDM2_0DDI_VIDEODEVICEFUNCS\s*\{(.*?)\}\s*D3DWDDM2_0DDI_VIDEODEVICEFUNCS;', h, re.S)
members = re.findall(r'(PFN\w+)\s+(pfn\w+)\s*;', m.group(1))
def typedef(t):
    mm = re.search(r'typedef\s+(\w+)\s*\(\s*APIENTRY\s*\*\s*' + t + r'\s*\)\s*\((.*?)\);', h, re.S)
    if not mm: raise SystemExit('typedef not found ' + t)
    ret, params = mm.group(1), mm.group(2)
    params = re.sub(r'//[^\n]*', '', params)
    parts, depth, cur = [], 0, ''
    for ch in params:
        if ch == '(': depth += 1
        if ch == ')': depth -= 1
        if ch == ',' and depth == 0: parts.append(cur); cur = ''
        else: cur += ch
    if cur.strip(): parts.append(cur)
    clean = []
    for p in parts:
        p = re.sub(r'_\w+_\s*\([^()]*(\([^()]*\))*[^()]*\)', ' ', p)   # _Out_writes_(x) etc.
        p = re.sub(r'\b_(In|Out|Inout)\w*_\b', ' ', p)
        tok = p.split()
        # "TYPE *pName": the star belongs to the type, the name is dropped
        if len(tok) >= 2 and re.fullmatch(r'\*+[A-Za-z_]\w*', tok[-1]):
            stars = re.match(r'\*+', tok[-1]).group(0)
            tok = tok[:-1]; tok[-1] = tok[-1] + stars
            clean.append(' '.join(tok)); continue
        # drop a trailing parameter name ("UINT Count", "CONST X* pDesc"); keep "CONST UINT"
        if len(tok) >= 2 and re.fullmatch(r'[A-Za-z_]\w*', tok[-1]) and tok[-2] not in ('CONST', 'const', 'unsigned', 'struct', 'enum'):
            tok = tok[:-1]
        clean.append(' '.join(tok))
    return ret, clean
SPECIAL = {
    'pfnGetVideoDecoderProfileCount': '*p1 = 0;',
    'pfnCheckVideoDecoderFormat': '*p3 = FALSE;',
    'pfnGetVideoDecoderConfigCount': None,  # filled below from its signature
    'pfnCheckVideoProcessorFormat': None,
    'pfnGetVideoProcessorCaps': None,
    'pfnGetVideoProcessorRateConversionCaps': None,
    'pfnGetContentProtectionCaps': None,
}
lines = ['/* Generated by tools/gen_d3d11_video_ddi_stubs.py from the pinned WDK 26100 d3d10umddi.h. Do not edit. */']
table = []
for idx, (t, name) in enumerate(members):
    ret, params = typedef(t)
    args = []
    for i, p in enumerate(params):
        if p in ('VOID', 'void', ''): continue
        args.append('%s p%d' % (p, i))
    sig = ', '.join(args) if args else 'VOID'
    fn = 'AgxVideoDdi_' + name[3:]
    body = ['   agx_video_ddi_receipt(%du);' % idx]
    special = ''
    if name == 'pfnGetVideoDecoderProfileCount': special = '   if (p1) *p1 = 0u;'
    elif name == 'pfnCheckVideoDecoderFormat': special = '   if (p3) *p3 = FALSE;'
    elif name == 'pfnGetVideoDecoderConfigCount': special = '   if (p%d) *p%d = 0u;' % (len(args) - 1, len(args) - 1)
    elif name == 'pfnCheckVideoProcessorFormat': special = '   if (p%d) *p%d = 0u;' % (len(args) - 1, len(args) - 1)
    elif name == 'pfnCheckVideoProcessorFormatConversion': special = '   if (p2) p2->Supported = FALSE;'
    elif name in ('pfnGetVideoProcessorCaps', 'pfnGetVideoProcessorRateConversionCaps', 'pfnGetContentProtectionCaps'):
        last = len(args) - 1
        special = '   if (p%d) memset(p%d, 0, sizeof(*p%d));' % (last, last, last)
    if not special and ret in ('VOID', 'void') and params:
        lp = params[-1]
        if lp.endswith('*') and not lp.upper().startswith('CONST') and lp.replace(' ', '').upper() not in ('VOID*', 'VOID**'):
            last = len(args) - 1
            special = '   if (p%d) memset(p%d, 0, sizeof(*p%d));' % (last, last, last)
    if special: body.append(special)
    if ret == 'HRESULT': body.append('   return E_NOTIMPL;')
    elif ret == 'SIZE_T': body.append('   return 64u;')
    elif ret in ('VOID', 'void'): pass
    else: body.append('   return (%s)0;' % ret)
    unused = ' '.join('(void)p%d;' % i for i, p in enumerate(params) if p not in ('VOID', 'void', ''))
    lines.append('static %s APIENTRY\n%s(%s)\n{\n   %s\n%s\n}' % (ret, fn, sig, unused, '\n'.join(body)))
    table.append('   f->%s = %s;' % (name, fn))
lines.append('#define AGX_VIDEO_DDI_ENTRIES %du' % len(members))
lines.append('static void\nagx_video_ddi_fill(D3DWDDM2_0DDI_VIDEODEVICEFUNCS *f)\n{\n' + '\n'.join(table) + '\n}')
open(out, 'w').write('\n'.join(lines) + '\n')
print('entries', len(members))
