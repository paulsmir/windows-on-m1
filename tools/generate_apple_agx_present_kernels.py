#!/usr/bin/env python3
"""Generate the KMD present-blt kernels header (G2 HW2).

Builds drivers/apple-agx/mesa/compiler-host/agx_present_kernels.c against the
pinned Mesa AGX compiler build (tools/build_apple_agx_shader_fixture.py), runs
it, and writes drivers/apple-agx/shared/include/
apple_agx_present_kernels.generated.h: the G13G binaries, the per-kernel
metadata the KMD needs for its USC words and CDM launch, the argument layout,
and the SHA-256 of the generator source and the Mesa commit they came from.

  python3 tools/generate_apple_agx_present_kernels.py --mesa-build DIR [--check]

--check regenerates into memory and fails when the checked-in header differs.
"""
import argparse
import hashlib
import json
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GENERATOR = ROOT / "drivers/apple-agx/mesa/compiler-host/agx_present_kernels.c"
HEADER = ROOT / "drivers/apple-agx/shared/include/apple_agx_present_kernels.generated.h"
LOCK = ROOT / "drivers/apple-agx/mesa/mesa-source.lock.json"
BUILD_TOOL = ROOT / "tools/build_apple_agx_shader_fixture.py"
KERNELS = (("copy", "Copy"), ("fill", "Fill"))


def generator_sha256():
    return hashlib.sha256(GENERATOR.read_bytes()).hexdigest()


def run_generator(mesa_build, directory):
    exe = Path(directory) / "agx_present_kernels"
    subprocess.run([sys.executable, str(BUILD_TOOL), "--mesa-build", str(mesa_build),
                    "--source", str(GENERATOR), "--output", str(exe)], check=True)
    out = Path(directory) / "out"
    out.mkdir()
    result = subprocess.run([str(exe), str(out)], check=True, capture_output=True, text=True)
    meta = json.loads(result.stdout)
    binaries = {name: (out / f"{name}.bin").read_bytes() for name, _ in KERNELS}
    return meta, binaries


def fnv1a64(data):
    value = 0xcbf29ce484222325
    for byte in data:
        value = ((value ^ byte) * 0x100000001b3) & 0xffffffffffffffff
    return value


def render(meta, binaries, mesa_commit):
    lines = [
        "/* Generated by tools/generate_apple_agx_present_kernels.py -- do not edit.",
        " * Source: drivers/apple-agx/mesa/compiler-host/agx_present_kernels.c",
        f" * Generator SHA-256: {generator_sha256()}",
        f" * Pinned Mesa: {mesa_commit} (G13G binaries, agx_compile_shader_nir). */",
        "#ifndef APPLE_AGX_PRESENT_KERNELS_GENERATED_H",
        "#define APPLE_AGX_PRESENT_KERNELS_GENERATED_H",
        "",
        f'#define APPLE_AGX_PRESENT_GENERATOR_SHA256 "{generator_sha256()}"',
        f'#define APPLE_AGX_PRESENT_MESA_COMMIT "{mesa_commit}"',
        f"#define APPLE_AGX_PRESENT_ARG_HALFS {meta['arg_halfs']}u",
        f"#define APPLE_AGX_PRESENT_LOCAL_X {meta['workgroup'][0]}u",
        f"#define APPLE_AGX_PRESENT_LOCAL_Y {meta['workgroup'][1]}u",
    ]
    for name, half in meta["args"].items():
        lines.append(f"#define APPLE_AGX_PRESENT_ARG_{name} {half}u")
    lines += [
        "",
        "typedef struct _APPLE_AGX_PRESENT_KERNEL {",
        "  const unsigned char *Binary;",
        "  unsigned int BinaryBytes, MainOffset, PreambleOffset;",
        "  unsigned int Gprs, PreambleGprs, PushCount;",
        "  unsigned int RodataOffset, RodataBaseUniform, RodataHalfs;",
        "  unsigned long long Fnv1a64;",
        "} APPLE_AGX_PRESENT_KERNEL;",
        "",
    ]
    for name, title in KERNELS:
        info = meta["kernels"][name]
        blob = binaries[name]
        if len(blob) != info["binary_bytes"] or fnv1a64(blob) != int(info["fnv1a64"], 16):
            raise ValueError(f"{name}: binary does not match its metadata")
        if info["workgroup"] != meta["workgroup"] or info["local_size"]:
            raise ValueError(f"{name}: workgroup or threadgroup memory changed")
        lines.append(f"static const unsigned char AppleAgxPresent{title}Binary[{len(blob)}] = {{")
        for offset in range(0, len(blob), 16):
            lines.append("  " + ", ".join(f"0x{b:02x}" for b in blob[offset:offset + 16]) + ",")
        lines.append("};")
        lines.append(f"static const APPLE_AGX_PRESENT_KERNEL AppleAgxPresent{title} = {{")
        lines.append(f"  AppleAgxPresent{title}Binary, {info['binary_bytes']}u, "
                     f"{info['main_offset']}u, {info['preamble_offset']}u,")
        lines.append(f"  {info['gprs']}u, {info['preamble_gprs']}u, {info['push_count']}u,")
        lines.append(f"  {info['rodata_offset']}u, {info['rodata_base_uniform']}u, "
                     f"{info['rodata_halfs']}u,")
        lines.append(f"  {info['fnv1a64']}ULL,")
        lines.append("};")
        lines.append("")
    lines.append("#endif")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--mesa-build", type=Path, required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    mesa_commit = json.loads(LOCK.read_text())["commit"]
    with tempfile.TemporaryDirectory() as directory:
        meta, binaries = run_generator(args.mesa_build, directory)
    text = render(meta, binaries, mesa_commit)
    if args.check:
        if HEADER.read_text() != text:
            print("apple_agx_present_kernels.generated.h is stale", file=sys.stderr)
            return 1
        return 0
    HEADER.write_text(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
