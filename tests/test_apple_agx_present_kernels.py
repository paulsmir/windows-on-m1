"""G2 HW2: the KMD present-blt kernels header is fresh and self-consistent.

What it catches: a generator edit without regeneration (the KMD would run
stale code), a header edited by hand (binary and metadata disagree), a Mesa
pin change without regeneration, and an argument block that overlaps the
compiler's own uniforms (the kernel would read its constants as arguments).
With the pinned toolchain present the header is regenerated byte for byte.
"""
from pathlib import Path
import hashlib
import json
import os
import re
import subprocess
import sys
import unittest

ROOT = Path(__file__).resolve().parents[1]
HEADER = ROOT / "drivers/apple-agx/shared/include/apple_agx_present_kernels.generated.h"
GENERATOR = ROOT / "drivers/apple-agx/mesa/compiler-host/agx_present_kernels.c"
LOCK = ROOT / "drivers/apple-agx/mesa/mesa-source.lock.json"
LOCAL = Path(os.environ.get("APPLE_AGX_LOCAL", ROOT.parents[1] / ".local"))
MESA_BUILD = LOCAL / "accelerated-desktop-ad03/mesa-build"
NINJA_BIN = LOCAL / "tooling/mesa-build-venv/bin"


def fnv1a64(data):
    value = 0xcbf29ce484222325
    for byte in data:
        value = ((value ^ byte) * 0x100000001b3) & 0xffffffffffffffff
    return value


def kernels(text):
    result = {}
    for title in ("Copy", "Fill"):
        blob = re.search(r"AppleAgxPresent%sBinary\[(\d+)\] = \{(.*?)\};" % title, text, re.S)
        record = re.search(r"AppleAgxPresent%s = \{(.*?)\};" % title, text, re.S)
        data = bytes(int(x, 16) for x in re.findall(r"0x([0-9a-f]{2})", blob.group(2)))
        fields = [int(x, 16) if x.startswith("0x") else int(x)
                  for x in re.findall(r"(0x[0-9a-f]+|\d+)(?:u|ULL)", record.group(1))]
        result[title] = (int(blob.group(1)), data, fields)
    return result


class PresentKernels(unittest.TestCase):
    def test_header_matches_generator_and_pin(self):
        text = HEADER.read_text()
        self.assertIn('APPLE_AGX_PRESENT_GENERATOR_SHA256 "%s"'
                      % hashlib.sha256(GENERATOR.read_bytes()).hexdigest(), text)
        self.assertIn('APPLE_AGX_PRESENT_MESA_COMMIT "%s"'
                      % json.loads(LOCK.read_text())["commit"], text)

    def test_binaries_match_metadata_and_layout(self):
        text = HEADER.read_text()
        halfs = int(re.search(r"APPLE_AGX_PRESENT_ARG_HALFS (\d+)u", text).group(1))
        args = {k: int(v) for k, v in re.findall(r"APPLE_AGX_PRESENT_ARG_(\w+) (\d+)u", text)
                if k != "HALFS"}
        self.assertTrue(args and all(v < halfs for v in args.values()))
        for title, (size, data, fields) in kernels(text).items():
            (binary_bytes, main, preamble, gprs, preamble_gprs, push, rodata_offset,
             rodata_base, rodata_halfs, digest) = fields
            self.assertEqual(size, len(data), title)
            self.assertEqual(binary_bytes, len(data), title)
            self.assertEqual(digest, fnv1a64(data), title)
            self.assertTrue(main % 64 == 0 and main < len(data), title)
            self.assertEqual(preamble != 0, preamble_gprs != 0, title)
            self.assertTrue(0 < gprs <= 256, title)
            # The arguments occupy u0..halfs-1; the compiler's constants and
            # pushes come after them (reserved_preamble).
            self.assertGreaterEqual(push, halfs, title)
            if rodata_halfs:
                self.assertGreaterEqual(rodata_base, halfs, title)
                self.assertLessEqual(rodata_offset + 2 * rodata_halfs, main, title)

    @unittest.skipUnless((MESA_BUILD / "build.ninja").exists() and (NINJA_BIN / "ninja").exists(),
                         "pinned Mesa AGX compiler build not present")
    def test_regenerates_byte_for_byte(self):
        env = dict(os.environ, PATH=f"{NINJA_BIN}:{os.environ.get('PATH', '')}")
        if sys.platform == "darwin" and "SDKROOT" not in env:
            env["SDKROOT"] = subprocess.run(["xcrun", "--show-sdk-path"], check=True,
                                            capture_output=True, text=True).stdout.strip()
        result = subprocess.run([sys.executable, str(ROOT / "tools/generate_apple_agx_present_kernels.py"),
                                 "--mesa-build", str(MESA_BUILD), "--check"],
                                env=env, capture_output=True, text=True)
        self.assertEqual(result.returncode, 0, result.stderr[-2000:])


if __name__ == "__main__":
    unittest.main()
